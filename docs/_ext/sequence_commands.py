"""Generate the measurement command reference from the bundled plugin tree."""

from __future__ import annotations

import tomllib
from importlib.metadata import EntryPoint
from pathlib import Path

import yaml
from docutils.nodes import make_id

_ENTRY_POINT_GROUP = "stoner_measurement.plugins"
_OUTPUT = "_generated/sequence_commands"
_GENERATED = ".. Generated by sequence_commands.py.\n\n"


def _toctree(pages: list[str]) -> str:
    entries = "\n".join(f"   /{_OUTPUT}/{page}" for page in pages)
    return f".. toctree::\n   :maxdepth: 3\n\n{entries}\n"


def _write_reference(app) -> None:
    """Write category pages and plugin docstrings before Sphinx reads sources."""
    from stoner_measurement.resources import (
        normalise_plugin_catalogue_config,
        resolve_plugin_catalogue,
    )

    root = Path(app.confdir).parent
    with (root / "pyproject.toml").open("rb") as manifest:
        entries = tomllib.load(manifest)["project"]["entry-points"][_ENTRY_POINT_GROUP]
    catalogue = root / "src/stoner_measurement/conf/plugin_catalogue.yaml"
    config = normalise_plugin_catalogue_config(yaml.safe_load(catalogue.read_text(encoding="utf-8")))
    classes = {key: EntryPoint(key, target, _ENTRY_POINT_GROUP).load() for key, target in entries.items()}
    plugins = {key: plugin_class() for key, plugin_class in classes.items()}
    pages = {}
    group_names = set()

    def add_pages(items: list[dict]) -> list[str]:
        names = []
        for item in items:
            if "plugin" in item:
                key = item["plugin"]
                label = item["label"]
                page = f"plugin-{key}"
                target = entries[key].replace(":", ".")
                body = f".. autoclass:: {target}\n   :no-index:\n\nPython API reference for :class:`~{target}`.\n"
            else:
                label = item["group"]
                base = f"group-{make_id(label) or 'category'}"
                page = base
                count = 2
                while page in group_names:
                    page = f"{base}-{count}"
                    count += 1
                group_names.add(page)
                body = _toctree(add_pages(item["items"]))
            pages[f"{page}.rst"] = f"{_GENERATED}{label}\n{'=' * len(label)}\n\n{body}"
            names.append(page)
        return names

    pages["index.inc"] = _GENERATED + _toctree(add_pages(resolve_plugin_catalogue(config, plugins)))
    output = Path(app.srcdir) / _OUTPUT
    output.mkdir(parents=True, exist_ok=True)
    for filename, content in pages.items():
        path = output / filename
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
    for path in output.glob("*.rst"):
        if path.name not in pages and path.read_text(encoding="utf-8").startswith(_GENERATED):
            path.unlink()


def setup(app):
    """Register the catalogue reference generator."""
    app.connect("builder-inited", _write_reference)
    return {"parallel_read_safe": True, "parallel_write_safe": True}
